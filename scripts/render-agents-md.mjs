import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = join(root, "web/static/agents.md");
const guideSourcePath = "docs/AGENT_GUIDE.md";
const headingDemotion = 2;
const sectionSeparator = "\n\n---\n\n";
const fencePattern = /^\s*(`{3,}|~{3,})/;
const headingPattern = /^(#{1,6})(\s+)/;

const referenceSources = [
  { path: "README.md", title: "Project README" },
  { path: "pi/README.md", title: "Raspberry Pi Setup" },
  { path: "docs/API.md", title: "API Contract" },
  { path: "docs/ARCHITECTURE.md", title: "Architecture" },
  { path: "docs/CONFIGURATION.md", title: "Configuration" },
  { path: "docs/DEPLOYMENT.md", title: "Deployment" },
  { path: "AGENTS.md", title: "Repository Agent Rules" },
];

function readRepoFile(path) {
  return readFileSync(join(root, path), "utf8").trim();
}

function demoteHeadings(markdown, by) {
  let fenceMarker = null;

  return markdown
    .split("\n")
    .map((line) => {
      const fence = fencePattern.exec(line);
      if (fence) {
        const marker = fence[1][0];
        fenceMarker = fenceMarker === marker ? null : marker;
        return line;
      }
      if (fenceMarker) {
        return line;
      }

      const heading = headingPattern.exec(line);
      if (!heading) {
        return line;
      }

      const level = Math.min(6, heading[1].length + by);
      return `${"#".repeat(level)}${line.slice(heading[1].length)}`;
    })
    .join("\n");
}

function renderReferenceSection({ path, title }) {
  return [
    `## ${title}`,
    "",
    `Source: \`${path}\``,
    "",
    demoteHeadings(readRepoFile(path), headingDemotion),
  ].join("\n");
}

function renderCompiledReference() {
  return referenceSources.map(renderReferenceSection).join(sectionSeparator);
}

function renderGuide() {
  return [
    "# RSDB Agent Guide",
    "",
    "Generated by `bun run build:agents` from committed repo files. Do not edit `web/static/agents.md` directly.",
    "",
    "Source repository: https://github.com/abhay/rsdb",
    "Live aggregate: https://rsdb.hackshare.com",
    "Live agent guide: https://rsdb.hackshare.com/agents.md",
    "",
    readRepoFile(guideSourcePath),
    "",
    "## Compiled Reference",
    "",
    "The following sections are copied from committed repo docs. Source headings",
    "are nested under this generated guide so the page keeps one readable outline.",
    "",
    renderCompiledReference(),
    "",
  ].join("\n");
}

writeFileSync(outputPath, renderGuide());
