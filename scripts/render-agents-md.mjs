import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = join(root, "web/static/agents.md");

const sources = [
  ["README.md", "Project README"],
  ["docs/API.md", "API Contract"],
  ["docs/ARCHITECTURE.md", "Architecture"],
  ["docs/CONFIGURATION.md", "Configuration"],
  ["docs/DEPLOYMENT.md", "Deployment"],
  ["AGENTS.md", "Repository Agent Rules"],
];

function readRepoFile(path) {
  return readFileSync(join(root, path), "utf8").trim();
}

const sourceSections = sources.map(([path, title]) => [
  `## ${title}`,
  "",
  `Source: \`${path}\``,
  "",
  readRepoFile(path),
].join("\n"));

const guide = [
  "# RSDB Agent Guide",
  "",
  "Generated by `bun run build:agents` from committed repo files. Do not edit this file directly.",
  "",
  "Source repository: https://github.com/abhay/rsdb",
  "Live aggregate: https://rsdb.hackshare.com",
  "Live agent guide: https://rsdb.hackshare.com/agents.md",
  "",
  "## Quick Context",
  "",
  "RSDB is a Rust ADS-B / Mode S receiver stack. Raspberry Pi receiver nodes run `rsdb-usb` next to an RTL-SDR and submit signed frame batches to `rsdb-aggregate`. The aggregate verifies allowlisted Ed25519 public keys, dedupes by `submission_id`, persists hot state in SQLite, and serves the public browser UI plus JSON/WebSocket APIs.",
  "",
  "Useful live URLs:",
  "",
  "- UI: https://rsdb.hackshare.com/",
  "- Status: https://rsdb.hackshare.com/status.json",
  "- Bootstrap: https://rsdb.hackshare.com/bootstrap.json",
  "- Aircraft: https://rsdb.hackshare.com/aircraft.json",
  "- Receivers: https://rsdb.hackshare.com/receivers.json",
  "- Schema: https://rsdb.hackshare.com/schema.json",
  "- Agent guide: https://rsdb.hackshare.com/agents.md",
  "- Agent guide alias: https://rsdb.hackshare.com/llms.txt",
  "- Crawler policy: https://rsdb.hackshare.com/robots.txt",
  "- WebSocket: wss://rsdb.hackshare.com/ws",
  "",
  "For receiver onboarding, create a local receiver seed with `./pi/init-receiver-node.sh https://rsdb.hackshare.com`, then open a PR adding only the public key to `deploy/fly/allowlist.txt`.",
  "",
  ...sourceSections,
  "",
].join("\n");

writeFileSync(outputPath, guide);
